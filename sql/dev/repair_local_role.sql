DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rgpapp') THEN
        CREATE ROLE rgpapp WITH LOGIN PASSWORD 'r9pAdmin7';
    ELSE
        ALTER ROLE rgpapp WITH LOGIN PASSWORD 'r9pAdmin7';
    END IF;
END $$;

ALTER DATABASE rgpdb OWNER TO rgpapp;
\connect rgpdb
GRANT ALL PRIVILEGES ON SCHEMA public TO rgpapp;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO rgpapp;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO rgpapp;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON TABLES TO rgpapp;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON SEQUENCES TO rgpapp;
